const assert = require('node:assert/strict');
const { sampleTrace, parseTrace, analyzeTrace, JOINTS } = require('./load-ts.cjs')('src/motion/analyze.ts');
const sample = sampleTrace();
const result = analyzeTrace(sample);
assert.equal(result.source, 'sample');
assert.equal(result.duration, 20);
assert.ok(Math.abs(Object.values(result.body).reduce((a,b) => a+b,0) - 1) < 1e-9);
assert.ok(Math.abs(result.space.reduce((a,b) => a+b,0) - 1) < 1e-9);
assert.ok(result.repeats > 20 && Math.abs(result.period - .5) < .05);
assert.ok(result.beatMatch > .9);
assert.ok(analyzeTrace(sample, 120, .25).beatMatch < .1, 'quarter-second offset misses half-second grid');
const arms = analyzeTrace(sampleTrace('arms'));
assert.ok(arms.body.leftWrist > result.body.leftWrist);
assert.ok(analyzeTrace(sampleTrace('travel')).space.filter(v=>v>0).length > result.space.filter(v=>v>0).length);
const still = {version:1,source:'imported',frames: [0,.1,.2,.3].map(t=>({t,joints:Object.fromEntries(JOINTS.map(j=>[j,{x:.5,y:.5}]))}))};
assert.equal(analyzeTrace(still).repeats, 0);
assert.equal(analyzeTrace(still).beatMatch, null);
assert.equal(analyzeTrace(still).space[4], 1);
const hidden = JSON.parse(JSON.stringify(sample));
hidden.frames.forEach(f => Object.values(f.joints).forEach(p=>p.confidence=0));
assert.equal(analyzeTrace(hidden).coverage, 0);
assert.equal(analyzeTrace(hidden).space.reduce((a,b)=>a+b,0), 0);
assert.equal(parseTrace(JSON.stringify(sample)).source, 'imported');
assert.throws(()=>parseTrace('{}'));
assert.throws(()=>parseTrace(JSON.stringify({...still,frames:[still.frames[0],still.frames[0],still.frames[2]]})));
assert.throws(()=>parseTrace(JSON.stringify({...still,frames:still.frames.map(f=>({...f,joints:{}}))})));
assert.throws(()=>analyzeTrace(sample,0));
assert.throws(()=>analyzeTrace(sample,120,11));
const gaps={...still,frames:still.frames.map((f,i)=>({...f,t:i*2}))};
assert.equal(analyzeTrace(gaps).coverage,0);
console.log('PASS: body proportions, spatial occupancy, periodic peaks, beat offsets, stillness, confidence, gaps and malformed traces');
