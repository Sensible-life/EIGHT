const assert = require('node:assert/strict');
const { bodySummary } = require('../load-ts.cjs')('src/projection/bodySummary.ts');
const pose = { t: 1, aspect: .75, lm: Array.from({ length: 33 }, () => [0.5, 0.5, .9]) };
const usage = { tracking_ok: true, segments: { head: .1, torso: .1, arm_l: .1, arm_r: .3, leg_l: .1, leg_r: .3 }, underused: ['arm_l', 'head'] };
const result = bodySummary(usage, pose);
assert.equal(result.upper, .5);
assert.equal(result.lower, .5);
assert.equal(result.underused.join(','), 'arm_l');
assert.equal(bodySummary({ ...usage, tracking_ok: false }, pose), null);
const hidden = { ...pose, lm: pose.lm.map(x => [...x]) }; hidden.lm[15][2] = .2;
assert.equal(bodySummary(usage, hidden), null);
hidden.lm[15][2] = NaN; assert.equal(bodySummary(usage, hidden), null);
assert.equal(bodySummary({ ...usage, segments: { ...usage.segments, arm_l: NaN } }, pose), null);
console.log('PASS: display aggregates exclude hidden or invalid body data');
