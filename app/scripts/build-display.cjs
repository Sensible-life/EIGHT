// Bundles src/tracking/display.ts (and everything it imports) into one ES module for the server's display page:
// server/app/static/tracking.js. The output is committed so the server runs without node; bundle.test.cjs checks
// that it matches the source. Run: npm run build:display
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const APP = path.join(__dirname, '..');
const OUT = path.join(APP, '../server/app/static/tracking.js');
const HEADER = '// Generated by app/scripts/build-display.cjs from app/src/tracking/display.ts. Do not edit.\n';

/** The bundle as text; with write, also saved to server/app/static/tracking.js. */
function build({ write }) {
  const result = esbuild.buildSync({
    absWorkingDir: APP, // path comments in the output stay the same wherever this runs from
    entryPoints: ['src/tracking/display.ts'], bundle: true, format: 'esm', target: 'es2020', legalComments: 'none', charset: 'utf8', write: false,
  });
  const code = HEADER + result.outputFiles[0].text;
  if (write) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, code);
  }
  return code;
}

module.exports = { build };
if (require.main === module) {
  build({ write: true });
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}
